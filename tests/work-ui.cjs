'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const mount = require('./renderer-harness.cjs');
const built = fs.readFileSync(process.argv[2], 'utf8');
const test = mount(built);
const $ = selector => test.document.querySelector(selector);
const open = key => test.click('#gfw-companion-dock [data-cp-dock-action="' + key + '"]');
const tick = () => test.api.companion.tick();
open('memo');
assert.equal($('#gfw-work-title').textContent, '猫爪便签');
$('#gfw-note-input').value = '<写报告>';
test.change('#gfw-note-reminder', 'half-hour');
test.click('#gfw-note-add');
assert.match($('#gfw-note-list').textContent, /<写报告>/);
assert.equal(test.api.companion.getState().work.notes.length, 1);
const due = test.api.companion.getState().work.notes[0].dueAt;
assert.equal(due, test.now() + 30 * 60000);
test.advance(30 * 60000);
tick();
assert.equal(test.api.companion.getState().work.notes[0].reminded, true);
assert.match($('#gfw-text').textContent, /猫爪提醒/);
test.click('.cp-note-check');
assert.match($('#gfw-text').textContent, /认真盖章/);
test.advance(1450);
assert.match($('#gfw-text').textContent, /偷偷补一个/);
assert.ok(test.api.companion.getState().work.notes[0].doneAt);

open('focus');
$('#gfw-focus-goal').value = '写完摘要';
for (const invalid of ['4', '121', '20.5']) {
  test.change('#gfw-work-duration', invalid);
  test.click('#gfw-work-start');
  assert.equal(test.api.companion.getState().timer.status, 'idle');
  assert.equal($('#gfw-work-duration-error').hidden, false);
}
test.change('#gfw-work-duration', '37');
test.click('#gfw-work-start');
assert.equal(test.api.companion.getState().timer.durationMs, 37 * 60000);
test.click('#gfw-work-pause');
open('memo');
open('focus');
assert.equal($('#gfw-work-pause').textContent, '继续');
test.click('#gfw-work-pause');
test.advance(37 * 60000);
tick();
assert.equal($('#gfw-work-check').hidden, false);
test.click('#gfw-work-done');
test.click('#gfw-work-done');
test.click('#gfw-work-off');
assert.match($('#gfw-work-summary').textContent, /完成便签 1 件.*专注 1 轮（37 分钟）.*完成目标 1 个/);
$('#gfw-bookmark-input').value = '  补第三节的 <图注>  ';
test.click('#gfw-bookmark-save');
assert.equal(test.api.companion.getState().work.bookmark, '补第三节的 <图注>');
test.click('#gfw-work-sleep');
assert.equal(test.api.companion.getState().sleeping, true);
assert.equal(test.api.getMetrics().left5hPct, null, '交互不替换已过期的官方额度');

const snapshot=test.api.companion.getState();
const restored=mount(built,{state:snapshot,config:{companion:{reactionSequences:false}}});
restored.click('#gfw-companion-dock [data-cp-dock-action="memo"]');
assert.match(restored.document.querySelector('#gfw-note-list').textContent,/猫爪已阅/);
assert.equal(restored.api.companion.getState().work.notes[0].reminded,true);
restored.click('#gfw-companion-dock [data-cp-dock-action="focus"]');
assert.match(restored.document.querySelector('#gfw-bookmark-preview').textContent,/补第三节的 <图注>/);
assert.equal(restored.document.querySelector('#gfw-focus-goal').value,'');
restored.click('#gfw-bookmark-use');
assert.equal(restored.document.querySelector('#gfw-focus-goal').value,'补第三节的 <图注>');
restored.click('#gfw-work-off');
assert.equal(restored.document.querySelector('#gfw-bookmark-input').value,'补第三节的 <图注>');
restored.document.querySelector('#gfw-bookmark-input').value='';
restored.click('#gfw-bookmark-save');
assert.equal(restored.api.companion.getState().work.bookmark,'');
restored.click('#gfw-companion-dock [data-cp-dock-action="focus"]');
assert.equal(restored.document.querySelector('#gfw-work-bookmark').hidden,true);
restored.click('#gfw-companion-dock [data-cp-dock-action="joker"]');
assert.equal(restored.document.querySelector('#gfw-work-panel').hidden,true);
assert.equal(restored.document.querySelector('#gfw-joker-table').hidden,false);
const defaults=mount(built,{config:{companion:{focusMinutes:42}}});
defaults.click('#gfw-companion-dock [data-cp-dock-action="focus"]');
defaults.change('#gfw-work-duration', '');
defaults.click('#gfw-work-start');
assert.equal(defaults.api.companion.getState().timer.durationMs, 42 * 60000);

const scheduled=mount(built);
const s=selector=>scheduled.document.querySelector(selector);
scheduled.click('#gfw-companion-dock [data-cp-dock-action="memo"]');
s('#gfw-note-input').value='整理会议记录';
scheduled.change('#gfw-note-reminder','custom');
assert.equal(s('#gfw-note-custom').hidden,false);
scheduled.click('#gfw-note-add');
assert.equal(scheduled.api.companion.getState().work.notes.length,0,'未填时间不能创建定时便签');
const reminder=new Date(scheduled.now()+60*60000);
reminder.setSeconds(0,0);
const localTime=date=>new Date(+date-date.getTimezoneOffset()*60000).toISOString().slice(0,16);
s('#gfw-note-time').value=localTime(new Date(scheduled.now()-60*60000));
scheduled.click('#gfw-note-add');
assert.equal(scheduled.api.companion.getState().work.notes.length,0,'拒绝过去的时间');
s('#gfw-note-time').value=localTime(reminder);
scheduled.click('#gfw-note-add');
assert.equal(scheduled.api.companion.getState().work.notes[0].dueAt,+reminder);
assert.equal(s('#gfw-note-custom').hidden,true);

const resumedNote=mount(built,{state:scheduled.api.companion.getState()});
const r=selector=>resumedNote.document.querySelector(selector);
const reopenNotes=()=>resumedNote.click('#gfw-companion-dock [data-cp-dock-action="memo"]');
reopenNotes();
resumedNote.click('.cp-note-focus');
assert.equal(r('#gfw-work-title').textContent,'猫猫陪工');
assert.equal(r('#gfw-focus-goal').value,'整理会议记录');
assert.equal(resumedNote.api.companion.getState().timer.status,'idle');
resumedNote.change('#gfw-work-duration','5');
resumedNote.click('#gfw-work-start');
reopenNotes();
resumedNote.click('.cp-note-focus');
assert.equal(r('#gfw-work-title').textContent,'猫爪便签');
assert.equal(resumedNote.api.companion.getState().timer.goal,'整理会议记录');
resumedNote.advance(+reminder-resumedNote.now());
resumedNote.api.companion.tick();
resumedNote.advance(2200);
resumedNote.api.companion.tick();
assert.equal(resumedNote.api.companion.getState().work.notes[0].reminded,true);
console.log('PASS: real memo entry, reminder, stamp sequence, shared focus, durable state, and day summary.');
