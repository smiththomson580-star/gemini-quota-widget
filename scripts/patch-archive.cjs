'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { patchArchive } = require('../src/archive-patcher.cjs');
const source = process.argv[2];
if (!source) throw Error('Original app.asar path is required.');
const hook = fs.readFileSync(path.join(__dirname, '..', 'src', 'desktop-hook.cjs'));
const { output, report } = patchArchive(source, hook);
const build = path.join(__dirname, '..', 'build');
fs.mkdirSync(build, { recursive: true });
fs.writeFileSync(path.join(build, 'app.patched.asar'), output);
fs.writeFileSync(path.join(build, 'archive-verification.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify({ changedFiles: report.changedFiles.length, verifiedPackedFiles: report.verifiedPackedFiles, bytes: output.length }));
